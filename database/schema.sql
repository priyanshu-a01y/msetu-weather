-- PostgreSQL schema for MSetu's JPA entities.
-- Run this against the Supabase database only when initializing a new schema.
-- The application currently uses Hibernate ddl-auto=update; this script is
-- provided for explicit, repeatable table initialization and does not drop data.

CREATE TABLE IF NOT EXISTS saved_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    country VARCHAR(255),
    normalized_name VARCHAR(255) NOT NULL UNIQUE,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS weather_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location VARCHAR(255) NOT NULL,
    country VARCHAR(255),
    temperature_c DOUBLE PRECISION NOT NULL,
    feels_like_c DOUBLE PRECISION NOT NULL,
    humidity INTEGER NOT NULL,
    wind_speed DOUBLE PRECISION NOT NULL,
    pressure INTEGER NOT NULL,
    description VARCHAR(255),
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_weather_observed ON weather_history (observed_at);
